// ── Brainstorm Sessions — CRUD helpers ──────────────────────────────
//
// Thin wrappers over the brainstorm_sessions table (migration
// 20260907_brainstorm_sessions.sql). One row = one user press of
// `Brainstorm`; columns are JSONB blobs typed by session-types.ts.
//
// Conventions match src/lib/objective-canvas/decision-log.ts:
//   • `db: any` — the supabase client is passed loose so the same
//     helpers work for the user-RLS client (route handlers) and the
//     service-role client (runner orchestrator).
//   • Telemetry / non-blocking ops soft-fail with console.warn — they
//     must NEVER break the user-facing flow.
//   • PRIMARY mutations (create, settle) throw on failure — the runner
//     needs to know if the session row didn't land so it can degrade
//     gracefully or surface an error in the panel.
//
// Spec: BRAINSTORM_MODULE_SPEC.md §5.

import { logDecision } from "@/lib/objective-canvas/decision-log";
import type {
  BrainstormCleanup,
  BrainstormCompletedMetadata,
  BrainstormGeneration,
  BrainstormPlan,
  BrainstormRanking,
  BrainstormSession,
  BrainstormSessionStatus,
  BrainstormStartedMetadata,
  BrainstormTargetKind,
  BrainstormUserIdea,
} from "./session-types";

// ── Create ──────────────────────────────────────────────────────────

export interface CreateSessionArgs {
  userId: string;
  spaceId: string;
  targetKind: BrainstormTargetKind;
  subObjectiveId?: string | null;
  entityId?: string | null;
  /** Auto-generated by the panel ("Brainstorm · 2026-05-29 · creative+contrarian+gap_fill")
   *  but caller can override. User can rename later. */
  title?: string | null;
  /** tldraw page id the panel created on the existing objective board.
   *  Stored here so reopen / collapse / library re-open all find it. */
  tldrawPageId?: string | null;
}

/** Insert a fresh brainstorm session row in `running` status. Plan is
 *  empty until Stage 1 commits via commitPlan(). Throws on failure —
 *  the runner cannot proceed without a session id. */
export async function createSession(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  args: CreateSessionArgs,
): Promise<BrainstormSession> {
  const { data, error } = await db
    .from("brainstorm_sessions")
    .insert({
      user_id: args.userId,
      space_id: args.spaceId,
      target_kind: args.targetKind,
      sub_objective_id: args.subObjectiveId ?? null,
      entity_id: args.entityId ?? null,
      title: args.title ?? null,
      tldraw_page_id: args.tldrawPageId ?? null,
      plan: {},
      generations: [],
      user_added_ideas: [],
      status: "running" satisfies BrainstormSessionStatus,
    })
    .select("*")
    .single();
  if (error || !data) {
    throw new Error(
      `[brainstorm/sessions] create failed: ${error?.message ?? "no row returned"}`,
    );
  }
  return data as BrainstormSession;
}

// ── Stage 1: commit plan + log brainstorm_started ──────────────────

export interface CommitPlanArgs {
  userId: string;
  spaceId: string;
  sessionId: string;
  plan: BrainstormPlan;
}

/** Persist the locked 3-intent plan and fire the brainstorm_started
 *  decision_log event. Returns true on success — failure here is
 *  soft (the runner can still try the divergence loop, it just won't
 *  re-hydrate the plan on reload). */
export async function commitPlan(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  args: CommitPlanArgs,
): Promise<boolean> {
  try {
    const { error } = await db
      .from("brainstorm_sessions")
      .update({ plan: args.plan })
      .eq("id", args.sessionId);
    if (error) {
      console.warn("[brainstorm/sessions] commit plan failed:", error.message);
      return false;
    }
  } catch (err) {
    console.warn(
      "[brainstorm/sessions] commit plan threw:",
      err instanceof Error ? err.message : String(err),
    );
    return false;
  }

  // Audible decision_log event — soft-fails on its own.
  const metadata: BrainstormStartedMetadata = {
    session_id: args.sessionId,
    target_kind: "sub_objective_picker", // Phase 1
    planned_intents: args.plan.intents,
    intent_reasons: args.plan.reasons,
  };
  void logDecision(db, {
    userId: args.userId,
    spaceId: args.spaceId,
    action: "brainstorm_started",
    metadata: metadata as unknown as Record<string, unknown>,
  });

  return true;
}

// ── Stage 2: append a divergence batch ──────────────────────────────

/** Append one /propose result to the session's generations[] array.
 *  Read-modify-write so concurrent appends serialise — the runner
 *  fires intents sequentially, so contention is not expected. Returns
 *  the new generations length on success, null on failure. */
export async function appendGeneration(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  sessionId: string,
  generation: BrainstormGeneration,
): Promise<number | null> {
  try {
    const { data: row, error: readErr } = await db
      .from("brainstorm_sessions")
      .select("generations")
      .eq("id", sessionId)
      .single();
    if (readErr || !row) {
      console.warn(
        "[brainstorm/sessions] append generation read failed:",
        readErr?.message ?? "no row",
      );
      return null;
    }
    const existing = (row.generations as BrainstormGeneration[]) ?? [];
    const next = [...existing, generation];
    const { error: writeErr } = await db
      .from("brainstorm_sessions")
      .update({ generations: next })
      .eq("id", sessionId);
    if (writeErr) {
      console.warn(
        "[brainstorm/sessions] append generation write failed:",
        writeErr.message,
      );
      return null;
    }
    return next.length;
  } catch (err) {
    console.warn(
      "[brainstorm/sessions] append generation threw:",
      err instanceof Error ? err.message : String(err),
    );
    return null;
  }
}


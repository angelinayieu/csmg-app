// ── Stage 4: ranking + settle + log brainstorm_completed ───────────

export interface SettleArgs {
  userId: string;
  spaceId: string;
  sessionId: string;
  ranking: BrainstormRanking;
  /** Brief one-liner for the library row, e.g. "12 candidates, top 3
   *  pinned, 2 user ideas added". Computed by the runner. */
  outcomeSummary: string;
}

/** Atomically: set ranking, flip status='settled', stamp settled_at,
 *  and fire brainstorm_completed. Critical mutation — throws if the
 *  row update fails (the panel needs settled state to render Stage 5). */
export async function settle(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  args: SettleArgs,
): Promise<void> {
  const settledAt = new Date().toISOString();
  const { error } = await db
    .from("brainstorm_sessions")
    .update({
      ranking: args.ranking,
      status: "settled" satisfies BrainstormSessionStatus,
      settled_at: settledAt,
      outcome_summary: args.outcomeSummary,
    })
    .eq("id", args.sessionId);
  if (error) {
    throw new Error(`[brainstorm/sessions] settle failed: ${error.message}`);
  }

  // Per-ribbon tally for the audible event.
  let nTop = 0;
  let nExplore = 0;
  let nTray = 0;
  for (const c of args.ranking.candidates) {
    if (c.ribbon === "green") nTop++;
    else if (c.ribbon === "amber") nExplore++;
    else nTray++;
  }

  const metadata: BrainstormCompletedMetadata = {
    session_id: args.sessionId,
    n_candidates: args.ranking.candidates.length,
    n_top: nTop,
    n_explore: nExplore,
    n_tray: nTray,
    latency_ms: args.ranking.latency_ms,
  };
  void logDecision(db, {
    userId: args.userId,
    spaceId: args.spaceId,
    action: "brainstorm_completed",
    metadata: metadata as unknown as Record<string, unknown>,
  });
}

// ── Stage 5: user-added ideas ───────────────────────────────────────

/** Append a sticky-note idea the user dropped on the brainstorm page.
 *  The runner / panel may later score it via patchUserIdea(). Soft-
 *  fails (the sticky still renders client-side from local state). */
export async function appendUserIdea(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  sessionId: string,
  idea: BrainstormUserIdea,
): Promise<boolean> {
  try {
    const { data: row, error: readErr } = await db
      .from("brainstorm_sessions")
      .select("user_added_ideas")
      .eq("id", sessionId)
      .single();
    if (readErr || !row) {
      console.warn(
        "[brainstorm/sessions] append idea read failed:",
        readErr?.message ?? "no row",
      );
      return false;
    }
    const existing = (row.user_added_ideas as BrainstormUserIdea[]) ?? [];
    const next = [...existing, idea];
    const { error: writeErr } = await db
      .from("brainstorm_sessions")
      .update({ user_added_ideas: next })
      .eq("id", sessionId);
    if (writeErr) {
      console.warn(
        "[brainstorm/sessions] append idea write failed:",
        writeErr.message,
      );
      return false;
    }
    return true;
  } catch (err) {
    console.warn(
      "[brainstorm/sessions] append idea threw:",
      err instanceof Error ? err.message : String(err),
    );
    return false;
  }
}

/** Patch a single user idea (typically: after the critique pass scores
 *  it). Soft-fails — the score chip on the sticky just won't appear. */
export async function patchUserIdea(
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  db: any,
  sessionId: string,
  ideaId: string,
  patch: Partial<BrainstormUserIdea>,
): Promise<boolean> {
  try {
    const { data: row, error: readErr } = await db
      .from("brainstorm_sessions")
      .select("user_added_ideas")
      .eq("id", sessionId)
      .single();
    if (readErr || !row) {
      console.warn(
        "[brainstorm/sessions] patch idea read failed:",
        readErr?.message ?? "no row",
      );
      return false;
    }
    const existing = (row.user_added_ideas as BrainstormUserIdea[]) ?? [];
    const next = existing.map((i) => (i.id === ideaId ? { ...i, ...patch } : i));
    const { error: writeErr } = await db
      .from("brainstorm_sessions")
      .update({ user_added_ideas: next })
      .eq("id", sessionId);
    if (writeErr) {
      console.warn(
        "[brainstorm/sessions] patch idea write failed:",
        writeErr.message,
      );
      return false;
    }
    return true;
  } catch (err) {
    console.warn(
      "[brainstorm/sessions] patch idea threw:",
      err instanceof Error ? err.message : String(err),
    );
    return false;
  }
}


// GET /api/brainstorm/space/[spaceId]/library/objects/[objectId]
//
// Single library_object + its back-half object-graph neighborhood (object_links
// touching it, with the other end's title/type). The read path behind the
// oc-card / Library object detail drawer (OPEN_CARD_DETAIL_EVENT). Soft-fails to
// { object: null, links: [] } so the drawer never throws.

import { NextResponse, type NextRequest } from "next/server";
import { safeAuth, verifySpaceOwnership } from "@/lib/api-helpers";
import { getLibraryObject } from "@/lib/objective-canvas/library-objects";

export const dynamic = "force-dynamic";

interface Ctx {
  params: Promise<{ spaceId: string; objectId: string }>;
}

export interface ObjectLinkRef {
  id: string;
  relation: string;
  direction: "out" | "in";
  title: string;
  type: string;
  subsystem?: string | null;
}

/** A library_objects sibling that shares the same `op:{opId}:` provenance prefix
 *  as the object being viewed — i.e. another row generated by the same operation
 *  (typically a "How it works" descriptor or a numbered flow step under a
 *  mechanism). The catalog collapses these under their parent; the drawer
 *  surfaces them inline so the parent's full breakdown is visible. */
export interface SiblingObjectRef {
  id: string;
  title: string;
  type: string;
  summary: string | null;
}

/** Image evidence for a context_concept row sourced from a vision extraction.
 *  The trace-back the user explicitly asked about: glossary term → concept_slug
 *  → context_concept row → THIS payload → the actual image + its narrative.
 *  Only populated when the concept has source_ingested_file_id in its
 *  content_snapshot and that file is still readable. */
export interface ImageEvidenceRef {
  ingestedFileId: string;
  imageUrl: string | null;
  sourceName: string | null;
  /** 2-4 sentence technical description from the vision pass. */
  description: string | null;
  /** Taste-aware prose tying the image to the objective + glossary. */
  narrative: string | null;
  /** The verbatim phrase this specific concept was lifted from
   *  (the entity's own description in the vision extraction). */
  sourcePhrase: string | null;
}

export async function GET(_req: NextRequest, ctx: Ctx) {
  const { supabase, user, error: authError } = await safeAuth();
  if (authError) return authError;

  const { spaceId, objectId } = await ctx.params;
  const isOwner = await verifySpaceOwnership(supabase, spaceId, user.id);
  if (!isOwner) {
    return NextResponse.json({ error: "Not authorized" }, { status: 403 });
  }

  const db = supabase as any;

  const object = await getLibraryObject(db, objectId);
  if (!object) {
    return NextResponse.json({ object: null, links: [] });
  }

  let links: ObjectLinkRef[] = [];
  try {
    const { data: rawLinks } = await db
      .from("object_links")
      .select("from_object_id, to_object_id, relation")
      .eq("space_id", spaceId)
      .or(`from_object_id.eq.${objectId},to_object_id.eq.${objectId}`);

    const rows: Array<{ from_object_id: string; to_object_id: string; relation: string }> =
      rawLinks ?? [];
    const otherIds = Array.from(
      new Set(
        rows.map((l) => (l.from_object_id === objectId ? l.to_object_id : l.from_object_id)),
      ),
    );

    const meta = new Map<string, { title: string; type: string; subsystem: string | null }>();
    if (otherIds.length) {
      const { data: others } = await db
        .from("library_objects")
        .select("id, title, object_type, subsystem")
        .in("id", otherIds);
      for (const o of (others ?? []) as Array<{
        id: string;
        title: string;
        object_type: string;
        subsystem: string | null;
      }>) {
        meta.set(o.id, { title: o.title, type: o.object_type, subsystem: o.subsystem ?? null });
      }
    }

    links = rows.map((l) => {
      const outgoing = l.from_object_id === objectId;
      const otherId = outgoing ? l.to_object_id : l.from_object_id;
      const m = meta.get(otherId);
      return {
        id: otherId,
        relation: l.relation,
        direction: outgoing ? "out" : "in",
        title: m?.title ?? "Untitled",
        type: m?.type ?? "object",
        subsystem: m?.subsystem ?? null,
      } as ObjectLinkRef;
    });
  } catch {
    links = [];
  }

  // ── Siblings (same op:{opId}: provenance prefix) ─────────────────────
  // The decompose / idea-mechanism ops emit one row per spec item ("How it
  // works" + numbered flow steps + root mechanism), all sharing an
  // `op:{opId}:` source_ref prefix. The catalog hides children under the
  // parent; the drawer surfaces them so the parent's full structure is
  // visible without forcing the user to open each row separately.
  let siblings: SiblingObjectRef[] = [];
  try {
    const sourceRef = (object as { source_ref?: string | null }).source_ref ?? null;
    if (sourceRef && sourceRef.startsWith("op:")) {
      const i = sourceRef.indexOf(":", 3);
      const prefix = i === -1 ? null : sourceRef.slice(0, i + 1); // "op:{opId}:"
      if (prefix) {
        const { data: sibs } = await db
          .from("library_objects")
          .select("id, title, object_type, summary")
          .eq("space_id", spaceId)
          .like("source_ref", `${prefix}%`)
          .neq("id", objectId)
          .neq("selection_status", "rejected");
        siblings = ((sibs ?? []) as Array<{
          id: string;
          title: string;
          object_type: string;
          summary: string | null;
        }>).map((s) => ({
          id: s.id,
          title: s.title,
          type: s.object_type,
          summary: s.summary,
        }));
      }
    }
  } catch {
    siblings = [];
  }

  // ── Image evidence (context_concept trace-back) ──────────────────────
  // When the concept was materialized from a vision extraction, hydrate
  // the source image so the drawer can render the trace-back panel.
  // Soft-fail → null; the drawer renders without the panel.
  let imageEvidence: ImageEvidenceRef | null = null;
  try {
    const objAny = object as { object_type?: string; content_snapshot?: unknown };
    if (objAny.object_type === "context_concept" && objAny.content_snapshot) {
      const snap = objAny.content_snapshot as Record<string, unknown>;
      const fileId =
        typeof snap.source_ingested_file_id === "string"
          ? snap.source_ingested_file_id
          : null;
      const sourcePhrase =
        typeof snap.source_phrase === "string" ? snap.source_phrase : null;
      if (fileId) {
        const { data: img } = await db
          .from("ingested_files")
          .select("id, image_url, source_name, image_description, image_narrative")
          .eq("id", fileId)
          .maybeSingle();
        if (img) {
          imageEvidence = {
            ingestedFileId: img.id as string,
            imageUrl: (img.image_url as string | null) ?? null,
            sourceName: (img.source_name as string | null) ?? null,
            description: (img.image_description as string | null) ?? null,
            narrative: (img.image_narrative as string | null) ?? null,
            sourcePhrase,
          };
        }
      }
    }
  } catch {
    imageEvidence = null;
  }

  return NextResponse.json({ object, links, siblings, imageEvidence });
}
